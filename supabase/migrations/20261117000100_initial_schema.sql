create table if not exists public.users (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email text not null unique,
  password_hash text not null,
  role text not null default 'Student' check (role in ('Student', 'Faculty', 'Admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.threads (
  id bigint generated by default as identity primary key,
  title text not null,
  course text not null,
  category text not null check (category in ('Question', 'Discussion')),
  author text not null,
  body text not null,
  votes integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  thread_id bigint not null references public.threads(id) on delete cascade,
  author text not null,
  role text not null check (role in ('Student', 'Faculty', 'Admin')),
  body text not null,
  verified boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.resources (
  id bigint generated by default as identity primary key,
  title text not null,
  course text not null,
  session text not null,
  format text not null,
  size text not null,
  uploaded_by text not null,
  created_at timestamptz not null default now(),
  file_name text,
  storage_key text
);

alter table public.resources add column if not exists file_name text;
alter table public.resources add column if not exists storage_key text;

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  summary text not null,
  required_skills text not null,
  owner text not null,
  match integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.project_interests (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(project_id, user_id)
);

create table if not exists public.moderation_items (
  id bigint generated by default as identity primary key,
  type text not null,
  title text not null,
  owner text not null,
  urgency text not null,
  status text not null,
  created_at timestamptz not null default now()
);

create index if not exists comments_thread_id_id_idx on public.comments(thread_id, id);
create index if not exists project_interests_user_id_idx on public.project_interests(user_id);

alter table public.users enable row level security;
alter table public.threads enable row level security;
alter table public.comments enable row level security;
alter table public.resources enable row level security;
alter table public.projects enable row level security;
alter table public.project_interests enable row level security;
alter table public.moderation_items enable row level security;

grant all on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.increment_thread_votes(p_thread_id bigint)
returns void
language sql
security definer
set search_path = public
as $$
  update public.threads
  set votes = votes + 1
  where id = p_thread_id;
$$;

revoke all on function public.increment_thread_votes(bigint) from public, anon, authenticated;
grant execute on function public.increment_thread_votes(bigint) to service_role;

